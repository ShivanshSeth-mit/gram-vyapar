/**
 * Returns a localized copy of GovernmentScheme based on active language.
 */
export function getLocalizedScheme(scheme: GovernmentScheme, lang: SupportedLanguage): GovernmentScheme {
  const trans = SCHEME_TRANSLATIONS[scheme.id]?.[lang];
  if (!trans) {
    // If not specifically translated to this dialect, check Hindi if applicable
    if (lang === "hi" && scheme.nameHi) {
      return { ...scheme, name: scheme.nameHi };
    }
    return scheme;
  }

  return {
    ...scheme,
    name: trans.name || (lang === "hi" && scheme.nameHi ? scheme.nameHi : scheme.name),
    conditionDescription: trans.conditionDescription || scheme.conditionDescription,
    reasoning: trans.reasoning || scheme.reasoning,
    subsidyAssistance: trans.subsidyAssistance || scheme.subsidyAssistance,
    highlightBadge: trans.highlightBadge || scheme.highlightBadge,
    targetBeneficiaries: trans.targetBeneficiaries || scheme.targetBeneficiaries,
    collateralRequirement: trans.collateralRequirement || scheme.collateralRequirement,
    eligibilityCriteria: trans.eligibilityCriteria || scheme.eligibilityCriteria,
    documentsRequired: trans.documentsRequired || scheme.documentsRequired
  };
}

/**
 * Returns a localized copy of PartnerBank based on active language.
 */
export function getLocalizedBank(bank: PartnerBank, lang: SupportedLanguage): PartnerBank {
  const trans = BANK_TRANSLATIONS[bank.id]?.[lang];
  if (!trans) {
    return bank;
  }

  return {
    ...bank,
    name: trans.name || bank.name,
    shortName: trans.shortName || bank.shortName,
    processingFeeText: trans.processingFeeText || bank.processingFeeText,
    ruralNetworkRating: trans.ruralNetworkRating || bank.ruralNetworkRating,
    branchTurnaround: trans.branchTurnaround || bank.branchTurnaround,
    specialPerks: trans.specialPerks || bank.specialPerks,
    portalName: trans.portalName || bank.portalName
  };
}

/**
 * Returns localized array of all available schemes for given language.
 */
export function getLocalizedSchemes(lang: SupportedLanguage): GovernmentScheme[] {
  return AVAILABLE_SCHEMES.map((s) => getLocalizedScheme(s, lang));
}

/**
 * Returns localized array of all partner banks for given language.
 */
export function getLocalizedBanks(lang: SupportedLanguage): PartnerBank[] {
  return PARTNER_BANKS.map((b) => getLocalizedBank(b, lang));
}
